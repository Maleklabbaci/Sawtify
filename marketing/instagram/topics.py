# ── Export du plan de contenu ─────────────────────────────────────────────
def export_plan() -> tuple[Path, Path]:
    OUT.mkdir(parents=True, exist_ok=True)
    csv_path = OUT / "PLAN-CONTENU.csv"
    md_path = OUT / "PLAN-CONTENU.md"

    with csv_path.open("w", newline="", encoding="utf-8") as fh:
        w = csv.writer(fh)
        w.writerow(["id", "categorie", "audience", "slides", "accroche", "promesse",
                    "argument 1", "argument 2", "argument 3", "slug"])
        for t in BANK:
            w.writerow([t["id"], t["cat"], t["audience"], t["shape"], t["hook"], t["sub"],
                        t["points"][0]["t"], t["points"][1]["t"], t["points"][2]["t"],
                        f"bank-{t['id']:03d}"])

    lines = ["# Plan de contenu — 300 sujets Sawtify (darija)", "",
             f"{len(BANK)} sujets · {sum(t['shape'] for t in BANK)} slides au total", ""]
    current = None
    for t in BANK:
        head = f"{t['cat']} — {t['audience']}"
        if head != current:
            lines += ["", f"## {head}", ""]
            current = head
        lines.append(f"- **{t['id']:03d}** · {t['shape']} slides · {t['hook']}")
    md_path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return csv_path, md_path


