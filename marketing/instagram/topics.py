def build_bank() -> list[dict]:
    """30 angles × 10 audiences = 300 sujets numérotés."""
    bank = []
    n = 0
    for angle in ANGLES:
        for aud in AUDIENCES:
            n += 1
            bank.append({
                "id": n,
                "cat": angle["cat"],
                "audience": aud["label"],
                "icon": aud["icon"],
                "shape": angle["shape"],
                "hook": angle["hook"].format(a=aud["label"], s=aud["short"]),
                "sub": angle["sub"],
                "points": [{"t": t.format(a=aud["label"], s=aud["short"]),
                            "v": v.format(a=aud["label"], s=aud["short"])}
                           for t, v in angle["points"]],
            })
    return bank


BANK = build_bank()


